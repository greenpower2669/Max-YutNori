function segment(x,y,a,b){
 const dx=b[0]-a[0],dy=b[1]-a[1],t=Math.max(0,Math.min(1,((x-a[0])*dx+(y-a[1])*dy)/(dx*dx+dy*dy)));
 return [Math.hypot(x-a[0]-t*dx,y-a[1]-t*dy),t];
}
function ribbon(x,y,paths){
 let value=0;
 for(const path of paths)for(let i=1;i<path.length;i++){
  const a=path[i-1],b=path[i];
  if(y<Math.min(a[1]-a[2],b[1]-b[2])||y>Math.max(a[1]+a[2],b[1]+b[2]))continue;
  for(const shift of [-1536,0,1536]){
   const xx=x+shift;
   if(xx<Math.min(a[0]-a[2],b[0]-b[2])||xx>Math.max(a[0]+a[2],b[0]+b[2]))continue;
   const [d,t]=segment(xx,y,a,b),width=a[2]+(b[2]-a[2])*t;
   value=Math.max(value,1-smooth(.4,1,d/width));
  }
 }
 return value;
}
function polygon(x,y,points,protectLand=false){
 let inside=false,distance=Infinity;
 for(let i=0,j=points.length-1;i<points.length;j=i++){
  const a=points[j],b=points[i];distance=Math.min(distance,segment(x,y,a,b)[0]);
  if((a[1]>y)!==(b[1]>y)&&x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0])inside=!inside;
 }
 const signed=inside?distance:-distance;
 // Give tiny islets a conservative shore margin so bilinear mask sampling
 // cannot pull surrounding animated water onto their rock pixels.
 return protectLand?smooth(-9,-3,signed):smooth(0,3,signed);
}
export function panoramaMasks(u,v){
 const x=u*1536,y=v*768;
 let fog=y>310&&y<690?ribbon(x,y,valleys):0;
 if(fog){
  let clearance=Infinity;
  for(const [cx,cy,rx,ry]of fallRegions){const dx=Math.abs(u-cx);clearance=Math.min(clearance,Math.hypot(Math.min(dx,1-dx)/rx,(v-cy)/ry));}
  // Fade before the protected region, rather than showing an elliptical cut.
  fog*=smooth(1,1.20,clearance);
 }
 const clouds=y<340?ribbon(x,y,sky)*(smooth(45,56,Math.hypot(x-1110,y-249))):0;
 let water=x>520&&x<1330&&y>378&&y<552?polygon(x,y,lake):0;
 if(water)for(const island of islands)water*=1-polygon(x,y,island,true);
 return [fog,clouds,water];
}
